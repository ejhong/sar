"""P2-07 · The whole chain: a satellite image of shaking ground over a chamber, through the published method.

    uv run python experiments/p2_07_whole_chain.py

P2-03 to P2-06 test the chain link by link. Here it runs whole, as the claim would have it.

1. Ground: the one-chamber bench (a 6 m air cube, centre 15 m down, sites/bench-void) under 100 m of open desert:
   scatterers uniformly at random, one per resolution cell, with forty brighter stones.
2. Shaking: microseisms at Giza's measured level (M1-01, 0.049 um/s over 0.1-0.3 Hz, plane Rayleigh waves from
   every direction, katabasis.ambient.field) and the chamber's imprint from P2-04's static kernels. Across 100 m the
   ground moves as u(x, t) = u0(t) + grad u(t) x + G K(x) : eps(t), to within (kL)^2, a few parts in a thousand.
3. The satellite: the real Giza dwell (P2-01), each Doppler bin at its own slow time, each row at its own zero-Doppler
   time; images in double precision, so that differences of a billionth of a radian survive.
4. The published method, as sarsim.pipeline implements it: 50 sub-aperture pairs of half the band 88 Hz apart, 32-pixel
   patch registration, the scene's common mode removed, and the focusing of Biondi & Malanga (2022, eqs. 21-24) with
   lambda_s = 0.48 m.

Scenarios: A, the chamber as it is (G = 1); B, the same ground with no chamber; and the chamber's imprint boosted G
times, up to where the method's output first changes visibly. Also the dwell's velocity series over the chamber (16
looks of 1.96 s, R4's reading) against a seismometer there.

The figures the site shows are written to the run's figs/ directory (images only; axes and labels are drawn by the site).
"""
