# ------------------------------------------------------------------ the scene
def scene(g, rng):
    Lx, Lr = SHAPE[0] * g.dx, SHAPE[1] * g.dr
    n = int((Lx / g.resolution) * (Lr / (0.886 / g.kr_band)))
    x = np.r_[rng.uniform(-Lx / 2, Lx / 2, n), rng.uniform(-Lx / 2.4, Lx / 2.4, N_STONES)]
    r = np.r_[rng.uniform(-Lr / 2, Lr / 2, n), rng.uniform(-Lr / 2.4, Lr / 2.4, N_STONES)]
    amp = np.r_[np.ones(n), rng.uniform(6, 20, N_STONES)]
    N = len(x)
    z = np.zeros(N)
    return Scatterers(x=x, y=r / np.sin(g.theta), z=z, amp=amp, phase=rng.uniform(0, 2 * np.pi, N), iso=np.ones(N),
                      flash=z, nu0=z, sig_nu=np.ones(N), vib_amp=z, vib_freq=z, vib_phase=z, label=np.zeros(N, int))


def kernels(g):
    """P2-04's line-of-sight imprint per unit strain (eps_ee, eps_nn, eps_en), interpolated on its 2 m grid."""
    path = RESULTS / 'p2_04_chamber_imprint' / 'kernels.npz'
    if not path.is_file():
        raise FileNotFoundError(f'{path} is regenerated by `uv run python experiments/p2_04_chamber_imprint.py`')
    K = np.load(path)
    xs, ys = np.unique(K['xy'][:, 0]), np.unique(K['xy'][:, 1])
    ix, iy = np.searchsorted(xs, K['xy'][:, 0]), np.searchsorted(ys, K['xy'][:, 1])
    los = np.asarray(g.los_enu)
    out = []
    for name in ('Kxx', 'Kyy', 'Kxy'):
        M = np.zeros((len(xs), len(ys)))
        M[ix, iy] = K[name] @ los
        out.append(RegularGridInterpolator((xs, ys), M, bounds_error=False, fill_value=0.0))
    return out


class Shaking:
    """The ground's slant-range increase at each scatterer and slow time: the synthesizer's motion callback."""

    def __init__(self, g, field, kern, gain):
        self.g, self.field, self.kern, self.gain = g, field, kern, gain
        self.los = np.asarray(g.los_enu)
        self.a, self.r = g.along_track_en, g.ground_range_en

    def lk(self, east, north):
        rr = np.hypot(east, north)
        taper = np.clip((TAPER[1] - rr) / (TAPER[1] - TAPER[0]), 0, 1)
        return np.stack([k(np.stack([east, north], 1)) for k in self.kern], 1) * taper[:, None]

    def basis(self, t):
        c = self.field.centre_series(t)
        eps = lambda G: np.stack([G[0, 0], G[1, 1], 0.5 * (G[0, 1] + G[1, 0])])
        S = np.vstack([self.los @ c['u'], c['g'].reshape(6, -1), eps(c['g'])])
        Sd = np.vstack([self.los @ c['u_dot'], c['g_dot'].reshape(6, -1), eps(c['g_dot'])])
        return S, Sd

    def coefficients(self, x, y):
        east = x * self.a[0] + y * self.r[0]
        north = x * self.a[1] + y * self.r[1]
        xj = np.stack([east, north], 1)
        grad = -(self.los[:, None, None] * xj.T[None, :, :]).reshape(6, -1).T
        return np.hstack([-np.ones((len(x), 1)), grad, -self.gain * self.lk(east, north)])

    def __call__(self, x, y, z, t):
        S, Sd = self.basis(t)
        C = self.coefficients(x, y)
        delta = self.g.zero_doppler_time(x)                 # each row's own zero-Doppler time, to first order
        return S.T @ C.T + Sd.T @ (C * delta[:, None]).T

    def los_velocity(self, east, north, t):
        """What a seismometer at (east, north) would record, projected on the line of sight (receding positive)."""
        S, Sd = self.basis(t)
        C = self.coefficients(*self._radar(east, north))
        return (Sd.T @ C.T)[:, 0]

    def imprint_phase(self, t):
        """Largest line-of-sight phase the imprint alone makes anywhere over the chamber (radians)."""
        S, _ = self.basis(t)
        e = np.linspace(-20, 20, 41)
        E, N = np.meshgrid(e, e, indexing='ij')
        lk = self.lk(E.ravel(), N.ravel())
        d = self.gain * (lk @ S[7:10])
        return float(4 * np.pi * np.abs(d).max() / self.g.lam)

    def _radar(self, east, north):
        p = np.array([[east, north]], float)
        return p @ self.a, p @ self.r


# ------------------------------------------------------------------ figures
def ramp(stops):
    from matplotlib.colors import LinearSegmentedColormap
    return LinearSegmentedColormap.from_list('u', stops)


RADAR = ramp(['#0b131c', '#1e2e3d', '#5d7386', '#b9c7d2', '#eef3f7'])
METHOD = ramp(['#101a24', '#3a2420', '#8e3b28', '#d46e50', '#f0a27f', '#fbe7dc'])
IMPRINT = ramp(['#2c5aa0', '#7fa3d6', '#16222e', '#d7b36e', '#be8a2e'])
STRENGTH = ramp(['#101a24', '#1c3150', '#2c5aa0', '#5b8fe0', '#a9c8f5', '#eef4fd'])


def ground_image(img, g, looks_az=4, looks_rg=1):
    """Amplitude on a ground grid: multilooked in intensity, slant range stretched to ground range, in dB."""
    I = np.abs(img) ** 2
    ny, nx = (I.shape[0] // looks_az) * looks_az, (I.shape[1] // looks_rg) * looks_rg
    I = I[:ny, :nx].reshape(ny // looks_az, looks_az, nx // looks_rg, looks_rg).mean(axis=(1, 3))
    stretch = g.dr * looks_rg / np.sin(g.theta) / (g.dx * looks_az)       # ground metres per column over per row
    cols = np.interp(np.arange(0, I.shape[1] - 1, 1 / stretch), np.arange(I.shape[1]), np.arange(I.shape[1]))
    I = np.stack([np.interp(cols, np.arange(I.shape[1]), row) for row in I])
    return 10 * np.log10(I + 1e-12)


def save(path, A, cmap, lo=None, hi=None):
    import matplotlib.pyplot as plt
    lo = np.percentile(A, 1) if lo is None else lo
    hi = np.percentile(A, 99.5) if hi is None else hi
    plt.imsave(path, np.clip((A - lo) / (hi - lo), 0, 1), cmap=cmap, vmin=0, vmax=1)
    return {'file': path.name, 'shape': list(A.shape), 'lo': float(lo), 'hi': float(hi)}


# ------------------------------------------------------------------ the run
def run_method(img, g, rows, cols, full=False):
    out = run_pipeline(img.astype(np.complex64), g, rows, cols, bank=SubapBank(), patch=PATCH, upsample=1000,
                       lam_s=LAM_S, modes=('paper',), verbose=False)
    if not full:
        return out['tomo_paper'], out['z']
    # the same focusing over one whole period of its depth axis, [0, 2 pi / dKz), for the viewer
    z_full = np.linspace(0.0, 2 * nyquist_depth(out['kz']), 320, endpoint=False)
    return out['tomo_paper'], out['z'], focus_paper(out['q'][..., 0] + 1j * out['q'][..., 1], out['kz'], z_full), z_full


def main():
    g = DwellGeometry.from_record('giza-20250827')
    amb = json.loads((SITES / 'ambient.json').read_text())
    level = amb['regional']['microseism_vertical_0.1_0.3_hz']['value']
    speed = amb['regional']['microseism_phase_speed']['value']
    rng = np.random.default_rng(71)
    f = np.linspace(0.1, 0.3, 21)
    field = microseisms(f, np.full(len(f), level ** 2 / 0.2), np.random.default_rng(72), per_bin=4, speed=speed,
                        hv=rayleigh_hv(3300.0, 1830.0))
    kern = kernels(g)
    scat = scene(g, rng)
    rows = np.arange(48, SHAPE[0] - 48, STRIDE[0])
    cols = np.arange(32, SHAPE[1] - 32, STRIDE[1])
    RR, CC = np.meshgrid(rows, cols, indexing='ij')
    x_rows = (rows - SHAPE[0] // 2) * g.dx
    c_mid = int(np.argmin(np.abs(cols - SHAPE[1] // 2)))
    params = {'geometry': 'giza-20250827', 'image_px': SHAPE, 'scatterers': scat.n, 'bright_stones': N_STONES,
              'microseisms_m_s': level, 'band_hz': [0.1, 0.3], 'phase_speed_m_s': speed, 'lam_s_m': LAM_S,
              'bank': {'K': 50, 'sub_frac': 0.5, 'delta_hz': 88.0}, 'patch_px': PATCH, 'targets': int(RR.size),
              'gains': GAINS}
    with Run(RID, 'The whole chain: a satellite image of shaking ground over a chamber', params) as run:
        figs = run.dir / 'figs'
        figs.mkdir(exist_ok=True)
        t_fine = np.linspace(-12.0, 12.0, 4801)
        # A and B: the chamber as it is, and no chamber, in double precision
        t0 = time.time()
        img_B = synthesize(scat, g, SHAPE, motion=Shaking(g, field, kern, 0.0), dtype=np.complex128)
        img_A = synthesize(scat, g, SHAPE, motion=Shaking(g, field, kern, 1.0), dtype=np.complex128)
        T_B, z, F_B, z_full = run_method(img_B, g, RR.ravel(), CC.ravel(), full=True)
        T_A, _, F_A, _ = run_method(img_A, g, RR.ravel(), CC.ravel(), full=True)
        print(f'  A and B: {time.time() - t0:.0f} s', flush=True)
        rel = lambda a, b: float(np.sqrt(np.mean(np.abs(a - b) ** 2)) / np.sqrt(np.mean(np.abs(b) ** 2)))
        foot = np.hypot(*np.meshgrid(x_rows, (cols - SHAPE[1] // 2) * g.dr / np.sin(g.theta), indexing='ij')).ravel() < 15
        A_vs_B = {'image_relative_difference': rel(img_A, img_B), 'method_relative_difference': rel(T_A, T_B),
                  'imprint_phase_rad': Shaking(g, field, kern, 1.0).imprint_phase(t_fine)}
        # the method's depth volumes with and without the chamber, for the viewer (not committed; rerun to regenerate)
        np.savez_compressed(run.dir / 'volumes.npz', A=F_A.astype(np.float32), B=F_B.astype(np.float32),
                            rows=rows, cols=cols, z=z_full, dx=g.dx, dr=g.dr, theta=g.theta)
        # the boost: how far must the imprint be multiplied before the method's output changes?
        sweep = []
        T_show, G_show = None, None
        for G in GAINS:
            t0 = time.time()
            img = synthesize(scat, g, SHAPE, motion=Shaking(g, field, kern, G))
            T, _ = run_method(img, g, RR.ravel(), CC.ravel())
            change = np.abs(T - T_B)
            prof = change[foot].mean(axis=0) / T_B.mean()
            sweep.append({'gain': G, 'imprint_phase_rad': Shaking(g, field, kern, G).imprint_phase(t_fine),
                          'method_relative_difference': rel(T, T_B),
                          'over_chamber': float(change[foot].mean() / T_B[foot].mean()),
                          'elsewhere': float(change[~foot].mean() / T_B[~foot].mean()),
                          'change_profile': prof,
                          'change_spread': [float(prof[5:-5].min() / prof[5:-5].mean()), float(prof[5:-5].max() / prof[5:-5].mean())]})
            print(f'  G={G:.0e}: {time.time() - t0:.0f} s, change over chamber {sweep[-1]["over_chamber"]:.3f}', flush=True)
            if T_show is None and sweep[-1]['over_chamber'] > 0.5:
                T_show, G_show = T, G
        if T_show is None:
            T_show, G_show = T, GAINS[-1]
        # the dwell against a seismometer over the chamber
        m = look_masks(g, SHAPE[0], R4_CENTRES, W)
        rr_, cc_ = slice(SHAPE[0] // 2 - PATCH // 2, SHAPE[0] // 2 + PATCH // 2), slice(SHAPE[1] // 2 - PATCH // 2, SHAPE[1] // 2 + PATCH // 2)
        sar = velocity_series(looks(img_A, m), g, rr_, cc_)
        seis = Shaking(g, field, kern, 1.0).los_velocity(0.0, 0.0, t_fine)
        tw = np.abs(t_fine) <= 1.2
        c0 = field.centre_series(t_fine)
        ground_trace = {'t_s': t_fine[::10], 'up_m_s': c0['u_dot'][2][::10]}     # the ground's own trembling, vertical
        compare = {'look_times_s': R4_CENTRES, 'satellite_m_s': sar - sar.mean(),
                   'seismometer_t_s': t_fine[tw][::4], 'seismometer_m_s': (seis - seis[tw].mean())[tw][::4],
                   'satellite_rms_m_s': float(np.std(sar)), 'seismometer_rms_m_s': float(np.std(seis[tw]))}
        # figures
        sections = lambda T: T.reshape(len(rows), len(cols), -1)[:, c_mid, :].T          # depth x azimuth
        hi = np.percentile(sections(T_B), 99.5)
        fig = {
            'simulated_ground': save(figs / 'simulated_ground.png', ground_image(img_B, g), RADAR),
            'speckle_zoom': save(figs / 'speckle_zoom.png',
                                 ground_image(img_B[SHAPE[0] // 2 - 200:SHAPE[0] // 2 + 200, 80:176], g, 1, 1), RADAR),
            'method_A': save(figs / 'method_A.png', sections(T_A), METHOD, 0.0, hi),
            'method_B': save(figs / 'method_B.png', sections(T_B), METHOD, 0.0, hi),
            'method_boosted': save(figs / 'method_boosted.png', sections(T_show), METHOD, 0.0, hi),
            'method_difference': save(figs / 'method_difference.png', np.abs(sections(T_A) - sections(T_B)), METHOD, 0.0, hi),
        }
        # two looks: 2 s apart (no shared spectrum) and 0.12 s apart (almost all shared)
        pair = looks(img_B, look_masks(g, SHAPE[0], [-1.0, 1.0, -0.06, 0.06], W))
        side = 16.0                                            # m of ground on each side of the zoom
        n_az, n_rg = int(side / g.dx), int(side * np.sin(g.theta) / g.dr)
        zoom = (slice(SHAPE[0] // 2 - n_az // 2, SHAPE[0] // 2 + n_az // 2),
                slice(SHAPE[1] // 2 - n_rg // 2, SHAPE[1] // 2 + n_rg // 2))
        lk_dB = lambda L: ground_image(L[zoom], g, 1, 1)
        lo_l, hi_l = np.percentile(lk_dB(pair[0]), 2), np.percentile(lk_dB(pair[0]), 99.5)
        for i, name in enumerate(('look_early', 'look_late', 'look_near_a', 'look_near_b')):
            fig[name] = save(figs / f'{name}.png', lk_dB(pair[i]), RADAR, lo_l, hi_l)
            fig[name]['side_m'] = side
        def corr(a, b):
            A, B = np.abs(a[zoom]) - np.abs(a[zoom]).mean(), np.abs(b[zoom]) - np.abs(b[zoom]).mean()
            return float((A * B).sum() / np.sqrt((A * A).sum() * (B * B).sum()))
        look_corr = {'two_seconds_apart': corr(pair[0], pair[1]), 'an_eighth_apart': corr(pair[2], pair[3])}
        # the imprint as a map over the chamber (line of sight, a wave along the look direction)
        e = np.linspace(-40, 40, 161)
        E, N = np.meshgrid(e, e, indexing='xy')
        lk = Shaking(g, field, kern, 1.0).lk(E.ravel(), N.ravel())
        phi = np.arctan2(g.ground_range_en[0], g.ground_range_en[1])
        s_, c_ = np.sin(phi), np.cos(phi)
        imap = (lk @ np.array([s_ * s_, c_ * c_, s_ * c_])).reshape(E.shape)[::-1]
        v = np.abs(imap).max()
        fig['imprint_map'] = save(figs / 'imprint_map.png', imap, IMPRINT, -v, v)
        fig['imprint_map']['extent_m'] = [-40, 40]
        from scipy.ndimage import zoom as upsample
        rms = np.asarray(load('p2_04_chamber_imprint')['imprint_map_los_per_strain_m'])
        fine = upsample(rms, 4, order=3)[::-1]
        fig['imprint_strength'] = save(figs / 'imprint_strength.png', fine, STRENGTH, 0.0, fine.max())
        fig['imprint_strength']['extent_m'] = [-40, 40]
        # real desert beside simulated, same size and processing (desktop only)
        real = None
        if PRODUCT.is_file():
            from sarsim.dwell import DwellProduct
            p = DwellProduct(PRODUCT)
            crop, origin = p.crop(*p.geolocate(*OPEN_PLATEAU), *SHAPE)
            fig['real_ground'] = save(figs / 'real_ground.png', ground_image(crop, g), RADAR)
            I_r, I_s = np.abs(crop) ** 2, np.abs(img_B) ** 2
            real = {'crop_origin': [int(v) for v in origin],
                    'contrast_real': float(I_r.std() / I_r.mean()), 'contrast_simulated': float(I_s.std() / I_s.mean())}
        elif (figs / 'real_ground.png').is_file():
            prev = load(RID)
            real, fig['real_ground'] = prev.get('real'), prev['figures'].get('real_ground')
        geom = {'azimuth_m': SHAPE[0] * g.dx, 'ground_range_m': SHAPE[1] * g.dr / np.sin(g.theta),
                'section_azimuth_m': [float(x_rows[0]), float(x_rows[-1])], 'depth_m': [float(z[0]), float(z[-1])],
                'chamber': {'centre_depth_m': 15.0, 'size_m': 6.0}, 'zoom_m': [400 * g.dx, 96 * g.dr / np.sin(g.theta)],
                'look_zoom_m': [240 * g.dx, 64 * g.dr / np.sin(g.theta)]}
        boosted = next(s for s in sweep if s['gain'] == G_show)
        prof = np.asarray(boosted['change_profile'])[5:-5]
        flat = (float(prof.min() / prof.mean()), float(prof.max() / prof.mean()))
        finding = (
            f"Run whole, the chain cannot tell the chamber is there. Over simulated desert shaking at Giza's measured "
            f"level, the chamber changes the satellite's image by {A_vs_B['image_relative_difference']:.0e} of itself "
            f"(its imprint is {A_vs_B['imprint_phase_rad']:.0e} rad of phase) and the published method's depth image by "
            f"{A_vs_B['method_relative_difference']:.0e}: with and without the chamber the pictures are the same. Its "
            f"imprint must be multiplied by {G_show:.0e} before the method's output changes visibly over it, and even then "
            f"the change is spread evenly over every depth it draws ({flat[0]:.2f} to {flat[1]:.2f} times its average): the "
            f"picture's texture is reshuffled, and nothing marks the chamber's depth. With the published settings the whole "
            f"depth axis ends at {z[-1]:.1f} m, above the chamber; another 'sound wavelength' only relabels the same "
            f"picture. Over "
            f"the chamber a seismometer records the ground moving at {compare['seismometer_rms_m_s'] * 1e6:.3f} um/s; the "
            f"dwell's velocity series wanders by {compare['satellite_rms_m_s'] * 1e6:.0f} um/s, "
            f"{compare['satellite_rms_m_s'] / compare['seismometer_rms_m_s']:.0f} times more, and not with it.")
        run.save({'geometry': geom, 'A_vs_B': A_vs_B, 'sweep': sweep, 'shown_gain': G_show, 'depth_axis_m': z,
                  'boosted_change_spread': flat, 'ground_trace': ground_trace,
                  'compare': compare, 'look_correlation': look_corr, 'real': real, 'figures': fig, 'finding': finding})
        print(finding)


if __name__ == '__main__':
    main()
